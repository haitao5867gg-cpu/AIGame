// 只有修仙改写；其余题材沿用 GENRE_STYLES（v2 旧版写法仍用 GENRE_STYLES，不受影响）。
const XUANHUAN_STORY = `【文风：玄幻修仙】
- 境界是读者的计分板：境界名和层数要常在正文里出现，修为变化写成能比较的事实（第几层、能做到什么、和谁比），不写「似乎强了一点」；门内身份、衣着、称呼按修为和辈分分高低。
- 压与扬：轻视和欺压要冲着主角来、当着人；压了两三节，就让主角的努力按情理换来一次小扬（一点收获、一次小胜、对手吃瘪），每章至少一次看得见的进展；扬的时候写围观的人怎么看（震惊、改口、后怕）。扬只能来自读者这回合行动的结果，不替读者出手。
- 主角有脑子也有嘴：做什么由读者定，但主角动手前心里先算一笔账（一两句具体的盘算），受了辱心里记一笔或冒一句狠话；该开口时按自己的腔调回嘴，别一节里反复「没说话」「点点头」。
- 金手指是主角最大的秘密（见任务书）：读者拿它试探时，写清试了什么、结果怎样、推出哪条规律、换来多少提升；一节最多摸清一条；处处防着被人看破。
- 每章至少让主角见一次「仙」：上位者随手一招、别人的法宝或丹药的效果，让人眼馋。斗法写招式的名字和样子、谁克谁、付出的代价、旁人的反应，以及输了会丢什么。
- 这个世界怎么修炼、门里怎么分高低，第一次出现时优先让在场的人在情境里说出来（师兄讲瓶颈、同屋讲管事的为人）；底层人说话可以粗。
- 篇幅按分量：重复的劳作和过场一两段带过，直接跳到下一个有事的时刻；同一个人的同一种刁难不写第三遍；天气和光线一节最多一句。
- 叙述冷静克制，用词带古意不晦涩。
- 收尾停在一句扎人的话（威胁、轻视、诱惑）、一个人登场、一个反常的发现，或局面突然翻转；少用景物和感觉收尾。`;

